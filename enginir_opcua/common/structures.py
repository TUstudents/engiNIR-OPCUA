"""
Support for custom structures in client and server
We only support a subset of features but should be enough
for custom structures
"""

from __future__ import annotations

import logging
import typing
from collections.abc import Callable
from dataclasses import field, make_dataclass
from enum import Enum, EnumMeta, IntEnum
from typing import TYPE_CHECKING, Any
from xml.etree import ElementTree as ET

from enginir_opcua import ua

from .structures104 import _NUMERIC_TYPES, _default_value_for, clean_name, get_default_value

if TYPE_CHECKING:
    from enginir_opcua.common.node import Node

_logger = logging.getLogger(__name__)


class EnumType:
    def __init__(self, name: str) -> None:
        self.name = clean_name(name)
        self.fields: list[EnumeratedValue] = []
        self.typeid: str | None = None

    def __str__(self) -> str:
        return f"EnumType({self.name, self.fields})"

    __repr__ = __str__

    def get_code(self) -> str:
        code = """

class {0}(IntEnum):

    '''
    {0} EnumInt autogenerated from xml
    '''

""".format(self.name)

        for EnumeratedValue in self.fields:
            name = clean_name(EnumeratedValue.Name)
            value = EnumeratedValue.Value
            code += f"    {name} = {value}\n"

        return code

    def build_class(self, env: dict[str, Any]) -> type:
        members = {clean_name(value.Name): value.Value for value in self.fields}
        cls = IntEnum(self.name, members)  # type: ignore[misc]
        cls.__doc__ = f"{self.name} EnumInt autogenerated from xml"
        return cls


class EnumeratedValue:
    def __init__(self, name: str, value: Any) -> None:
        if name == "None":
            name = "None_"
        name = name.replace(" ", "")
        self.Name = name
        self.Value = int(value)


class Struct:
    def __init__(self, name: str) -> None:
        self.name = clean_name(name)
        self.fields: list[Field] = []
        self.typeid: str | None = None
        self.option_counter = 0

    def __str__(self) -> str:
        return f"Struct(name={self.name}, fields={self.fields}"

    __repr__ = __str__

    def get_code(self) -> str:
        code = f"""

@dataclass(slots=True)
class {self.name}:

    '''
    {self.name} structure autogenerated from xml
    '''

"""
        for sfield in self._fields_with_encoding():
            uatype = sfield.annotation()
            if sfield.is_optional:
                code += f"    {sfield.name}: Optional[{uatype}] = None\n"
            else:
                uavalue = sfield.value
                if isinstance(uavalue, str) and uavalue.startswith("ua."):
                    uavalue = f"field(default_factory=lambda: {uavalue})"
                code += f"    {sfield.name}:'{uatype}' = {uavalue}\n"
        return code

    def _fields_with_encoding(self) -> list[Field]:
        """
        SwitchFields is the 'Encoding' Field in OptionSets to be
        compatible with 1.04 structs we added
        the 'Encoding' Field before and skip the SwitchField Field
        """
        fields = [sfield for sfield in self.fields if sfield.name != "SwitchField"]
        if self.option_counter > 0:
            encoding = Field("Encoding")
            encoding.uatype = "UInt32"
            fields = [encoding, *fields]
        return fields

    def build_class(self, env: dict[str, Any]) -> type:
        spec: dict[str, tuple[str, Any]] = {}
        for sfield in self._fields_with_encoding():
            annotation = sfield.resolved_annotation(env)
            if sfield.name == "Encoding":
                spec[sfield.name] = (annotation, None)
            elif sfield.is_optional:
                optional = f"typing.Optional[{annotation}]" if isinstance(annotation, str) else annotation | None
                spec[sfield.name] = (optional, None)
            elif sfield.array:
                spec[sfield.name] = (annotation, field(default_factory=list))
            else:
                spec[sfield.name] = (annotation, _default_for_type(sfield.uatype, env, sfield.enum_value))
        cls = make_dataclass(
            self.name,
            [(name, annotation, default) for name, (annotation, default) in spec.items()],
            namespace={"ua": ua, "typing": typing},
            slots=True,
        )
        cls.__module__ = __name__
        cls.__doc__ = f"{self.name} structure autogenerated from xml"
        return cls


class Field:
    def __init__(self, name: str) -> None:
        self.name = name
        self.uatype: str | None = None
        self.value: Any = None
        self.enum_value: int | None = None
        self.array = False
        self.is_optional = False

    def __str__(self) -> str:
        return f"Field(name={self.name}, uatype={self.uatype})"

    __repr__ = __str__

    def annotation(self) -> str:
        uatype = f"ua.{self.uatype}"
        if self.array:
            uatype = f"list[{uatype}]"
        if uatype == "list[ua.Char]":
            uatype = "ua.String"
        return uatype

    def resolved_annotation(self, env: dict[str, Any]) -> Any:
        found = env.get(self.uatype or "")
        if not isinstance(found, type):
            return self.annotation()
        return list[found] if self.array else found  # type: ignore[valid-type]


def _lookup_type(name: str, env: dict[str, Any]) -> Any:
    found = env.get(name)
    if isinstance(found, type):
        return found
    return getattr(ua, name, None)


_PLAIN_DEFAULT_TYPES = (
    frozenset(("String", "Guid", "ByteString", "CharArray", "Char", "Boolean", "DateTime")) | _NUMERIC_TYPES
)


def _default_for_type(uatype: str | None, env: dict[str, Any], enum_value: int | None = None) -> Any:
    name = uatype or ""
    cls = _lookup_type(name, env)
    if isinstance(cls, type) and issubclass(cls, Enum):
        if enum_value is not None:
            return cls(enum_value)
        return next(iter(cls.__members__.values()))
    base_name = cls.__name__ if isinstance(cls, type) else name
    if base_name in _PLAIN_DEFAULT_TYPES:
        return _default_value_for(base_name)
    factory: Callable[[], Any] = lambda: _lookup_type(name, env)()  # noqa: E731
    return field(default_factory=factory)


class StructGenerator:
    def __init__(self) -> None:
        self.model: list[EnumType | Struct] = []

    def make_model_from_string(self, xml: str | bytes) -> None:
        obj = ET.fromstring(xml)
        self._make_model(obj)

    def make_model_from_file(self, path: str) -> None:
        obj = ET.parse(path)
        root = obj.getroot()
        self._make_model(root)

    def _make_model(self, root: ET.Element) -> None:
        enums = {}
        for child in root:
            if child.tag.endswith("EnumeratedType"):
                intenum = EnumType(child.get("Name"))
                for xmlfield in child:
                    if xmlfield.tag.endswith("EnumeratedValue"):
                        name = xmlfield.get("Name")
                        value = xmlfield.get("Value")
                        enumvalue = EnumeratedValue(name, value)
                        intenum.fields.append(enumvalue)
                        enums[child.get("Name")] = enumvalue.Value
                self.model.append(intenum)

        for child in root:
            if child.tag.endswith("StructuredType"):
                struct = Struct(child.get("Name"))
                length_fields = {
                    xmlfield.get("LengthField")
                    for xmlfield in child
                    if xmlfield.tag.endswith("Field") and xmlfield.get("LengthField")
                }
                for xmlfield in child:
                    if xmlfield.tag.endswith("Field"):
                        name = xmlfield.get("Name")
                        _clean_name = clean_name(name)
                        if name in length_fields:
                            continue
                        array = bool(xmlfield.get("LengthField"))
                        _type = xmlfield.get("TypeName") or ""
                        if ":" in _type:
                            _type = _type.split(":")[1]
                        if _type == "Bit":
                            # Bits are used for bit fields and filler ignore
                            continue
                        field = Field(_clean_name)
                        field.uatype = clean_name(_type)
                        if xmlfield.get("SwitchField", "") != "":
                            # Optional Field
                            field.is_optional = True
                            struct.option_counter += 1
                        field.value = get_default_value(field.uatype, enums, hack=True)
                        if field.uatype in enums:
                            field.enum_value = enums[field.uatype]
                        if array:
                            field.array = True
                            field.value = "field(default_factory=list)"
                        struct.fields.append(field)
                self.model.append(struct)

    def save_to_file(self, path: str, register: bool = False) -> None:
        _file = open(path, "w+")
        self._make_header(_file)
        for struct in self.model:
            _file.write(struct.get_code())
        if register:
            _file.write(self._make_registration())
        _file.close()

    def _make_registration(self) -> str:
        code = "\n\n"
        for struct in self.model:
            if isinstance(struct, EnumType) or struct.typeid is None:
                continue
            code += (
                f"ua.register_extension_object('{struct.name}',"
                f" ua.NodeId.from_string('{struct.typeid}'), {struct.name})\n"
            )
        return code

    def get_python_classes(self, env: dict[str, Any] | None = None) -> dict[str, Any]:
        return _generate_python_class(self.model, env=env)

    def _make_header(self, _file: Any) -> None:
        _file.write("""
'''
THIS FILE IS AUTOGENERATED, DO NOT EDIT!!!
'''
from __future__ import annotations

from datetime import datetime, timezone
import uuid
from dataclasses import dataclass, field
from typing import Union, Optional
from enum import IntEnum

from enginir_opcua import ua
""")

    def set_typeid(self, name: str, typeid: str) -> None:
        for struct in self.model:
            if struct.name == name:
                struct.typeid = typeid
                return


async def load_type_definitions(
    server: Any, nodes: list[Node] | None = None
) -> tuple[list[StructGenerator], dict[str, Any]]:
    """
    Download xml from given variable node defining custom structures.
    If no node is given, attempts to import variables from all nodes under
    "0:OPC Binary"
    the code is generated and imported on the fly. If you know the structures
    are not going to be modified it might be interesting to copy the generated files
    and include them in you code
    """
    if nodes is None:
        nodes = []
        for desc in await server.nodes.opc_binary.get_children_descriptions():
            if desc.BrowseName != ua.QualifiedName("Opc.Ua"):
                nodes.append(server.get_node(desc.NodeId))

    types = server.types
    structs_dict: dict[str, Any] = {}
    generators = []
    for node in nodes:
        xml = await node.read_value()
        generator = StructGenerator()
        generators.append(generator)
        generator.make_model_from_string(xml)
        generator.get_python_classes(structs_dict)

        for ndesc in await node.get_children_descriptions():
            ndesc_node = server.get_node(ndesc.NodeId)
            ref_desc_list = await ndesc_node.get_references(
                refs=ua.ObjectIds.HasDescription, direction=ua.BrowseDirection.Inverse
            )
            if ref_desc_list:  # some server put extra things here
                name = clean_name(ndesc.BrowseName.Name)
                if name not in structs_dict:
                    _logger.warning("%s is found as child of binary definition node but is not found in xml", name)
                    continue
                nodeid = ref_desc_list[0].NodeId
                data_types = await server.get_node(nodeid).get_references(
                    refs=ua.ObjectIds.HasEncoding, direction=ua.BrowseDirection.Inverse
                )
                types.register_struct(data_types[0].NodeId if data_types else None, nodeid, structs_dict[name], name)
                generator.set_typeid(name, nodeid.to_string())

        await _register_enums(server, structs_dict)

    return generators, structs_dict


def _generate_python_class(model: list[Any], env: dict[str, Any] | None = None) -> dict[str, Any]:
    """
    Build Python classes for the parsed model and add them to env
    return a dict of structures {name: class}
    The classes are built directly from the parsed names and values; no code
    received from the server is ever executed.
    """
    if env is None:
        env = {}
    for element in model:
        env[element.name] = element.build_class(env)
    return env


async def _register_enums(server: Any, classes: dict[str, Any]) -> None:
    from enginir_opcua.ua.uatypes import _set_ua_attribute

    enum_nodes = {
        clean_name(desc.BrowseName.Name): desc.NodeId
        for desc in await server.nodes.enum_data_type.get_children_descriptions(refs=ua.ObjectIds.HasSubtype)
    }
    for name, cls in classes.items():
        if not isinstance(cls, EnumMeta) or name == "IntEnum":
            continue
        nodeid = enum_nodes.get(name)
        if nodeid is None:
            _set_ua_attribute(name, cls, None)
        elif server.types.find_own(nodeid) is None:
            server.types.register_enum(nodeid, cls, name)


async def load_enums(server: Any, env: dict[str, Any] | None = None, force: bool = False) -> dict[str, Any]:
    """
    Read enumeration data types on server, generate python Enums for them and register them in the type registry
    of the server or client
    """
    model = []
    nodeids: dict[str, ua.NodeId] = {}

    for desc in await server.nodes.enum_data_type.get_children_descriptions(refs=ua.ObjectIds.HasSubtype):
        enum_name = desc.BrowseName.Name
        enum_node = server.get_node(desc.NodeId)
        if not force and server.types.find_own(desc.NodeId) is not None:
            _logger.debug("Enum type %s is already registered, ignoring", enum_name)
            continue
        c = None
        for child_desc in await enum_node.get_children_descriptions(refs=ua.ObjectIds.HasProperty):
            child_node = server.get_node(child_desc.NodeId)
            if child_desc.BrowseName.Name == "EnumStrings":
                c = await _get_enum_strings(enum_name, child_node)
            elif child_desc.BrowseName.Name == "EnumValues":
                c = await _get_enum_values(enum_name, server.get_node(child_desc.NodeId))
            else:
                _logger.warning("Unexpected children of node %s: %s", desc, child_desc)
        if c is not None:
            model.append(c)
            nodeids[c.name] = desc.NodeId
    classes = _generate_python_class(model, env=env)
    for element in model:
        server.types.register_enum(nodeids[element.name], classes[element.name], element.name)
    return classes


async def _get_enum_values(name: str, node: Node) -> EnumType:
    val = await node.read_value()
    c = EnumType(name)
    c.fields = [EnumeratedValue(enumval.DisplayName.Text, enumval.Value) for enumval in val]
    return c


async def _get_enum_strings(name: str, node: Node) -> EnumType:
    val = await node.read_value()
    c = EnumType(name)
    c.fields = [EnumeratedValue(st.Text, idx) for idx, st in enumerate(val)]
    return c
