import nodeset_source

BASE_DIR = nodeset_source.BASE_DIR

if __name__ == "__main__":
    inputfile = open(nodeset_source.NODE_IDS_CSV)
    outputfile = open(BASE_DIR / "enginir_opcua" / "ua" / "object_ids.py", "w")
    outputfile.write(
        f"# AUTOGENERATED!!! {nodeset_source.provenance()}\n"
        f"\n"
        f"\n"
        # Making ObjectIds inherit IntEnum has a huge performance impact!!!!!
        # so we use a normal class and a reverse one for the few places we need it
        f"class ObjectIds:\n"
        f"    Null = 0\n"
    )
    nb = None
    name = None
    for line in inputfile:
        name, nb, datatype = line.split(",")
        outputfile.write(f"    {name} = {nb}\n")
    inputfile.close()
    inputfile = open(nodeset_source.NODE_IDS_CSV)
    outputfile.write("\n\nObjectIdNames = {}\nObjectIdNames[0] = 'Null'\n")
    for line in inputfile:
        name, nb, datatype = line.split(",")
        outputfile.write("ObjectIdNames[{0}] = '{1}'\n".format(nb, name))

    reference_type_ids = []
    with open(nodeset_source.NODE_IDS_CSV) as inputfile:
        for line in inputfile:
            name, nb, datatype = line.split(",")
            if datatype.strip() == "ReferenceType":
                reference_type_ids.append(int(nb))
    outputfile.write("\n\nReferenceTypeIds = frozenset({\n")
    for nb in reference_type_ids:
        outputfile.write(f"    {nb},\n")
    outputfile.write("})\n")

    inputfile = open(nodeset_source.ATTRIBUTE_IDS_CSV)
    outputfile = open(BASE_DIR / "enginir_opcua" / "ua" / "attribute_ids.py", "w")
    outputfile.write(
        f"# AUTOGENERATED!!! {nodeset_source.provenance()}\n"
        f"\n"
        f"from enum import IntEnum\n"
        f"\n"
        f"\n"
        f"class AttributeIds(IntEnum):\n"
    )
    for line in inputfile:
        name, nb = line.split(",")
        outputfile.write("    {0} = {1}\n".format(name.strip(), nb.strip()))

    print("generate done!")
